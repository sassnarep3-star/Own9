def _n(value):
    """A count is printed as a count; the absence of a row is printed as a dash, never a zero."""
    return str(value)


def _teams_table():
    headers = ['Club', 'Game block as published', 'Rows on the report', 'Out', 'Doubtful',
               'Questionable', 'Confirmed unavailable (Out + Doubtful)', 'Conditional (Questionable)',
               'Practice designation, no game status', 'Did not participate', 'Limited', 'Full',
               'Net report count (confirmed + conditional)']
    rows = []
    for c in _CLUBS:
        net = c['confirmed_unavailable'] + c['conditional']
        rows.append(row([c['club'] + ' · ' + c['nickname'], c['game'], _n(c['listed']), _n(c['out']),
                         _n(c['doubtful']), _n(c['questionable']), _n(c['confirmed_unavailable']),
                         _n(c['conditional']), _n(c['practice_only']), _n(c['dnp']), _n(c['limited']),
                         _n(c['full']), _n(net)],
                        _BOTH, 'Counted from the retained official capture'))
    t = _TOT
