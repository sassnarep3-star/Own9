def _point_in_time_table():
    rows = []
    for g in _GAMES:
        mins = g['minutes_from_capture']
        rows.append(row([g['day'] + ' · ' + g['kickoff_as_published'],
                         ' at '.join(g['clubs']) if len(g['clubs']) == 2 else ' / '.join(g['clubs']),
                         _n(g['rows']), g['kickoff_utc'],
                         ('+' if mins > 0 else '') + str(mins),
                         g['state']],
                        _BOTH, 'Kickoff and rows from the same capture page; capture clock from its manifest'))
    pre = sum(1 for g in _GAMES if g['state'] == 'before kickoff')
    rows.append(row(['Summary', str(pre) + ' of ' + str(len(_GAMES)) + ' game blocks were still '
                     'pre-kickoff when the only retained capture was taken',
                     str(sum(g['rows'] for g in _GAMES if g['state'] == 'before kickoff')),
                     _CAP['retrieved_at_utc'],
                     'closest was ' + str(min(abs(g['minutes_from_capture']) for g in _GAMES)) +
                     ' minutes from kickoff',
                     'a capture taken this late cannot replay pre-kickoff certainty'],
                    _REPO, 'Arithmetic on the rows above'))
    return table('Point-in-time position of the only retained availability capture',
                 ['Game block as published', 'Clubs, as the page lists them (away at home)',
                  'Rows on the report', 'Kickoff in UTC',
                  'Minutes from the capture to kickoff (negative means the kickoff had passed)',
                  'Position'], rows)


